/** 장소 한 줄 설명 조회 — displayName 키. 미등록이면 한글 원문 반환 */
export function localizedPlaceDesc(displayName: string, koDesc: string, locale: "ko" | "en"): string {
  return locale === "en" ? PLACE_DESC_EN[displayName] ?? koDesc : koDesc;
}

/**
 * 장소명 로마자 표기 조회. 미등록이면 한글 원문 반환(기존 fallback 정책 준수).
 * 개발 모드에서는 누락을 console.warn으로 노출한다.
 */
export function placeNameEn(name: string): string {
  const mapped = PLACE_NAME_EN[name];
  if (mapped) return mapped;
  if (process.env.NODE_ENV === "development" && /[가-힣]/.test(name)) {
    console.warn(`[i18n] PLACE_NAME_EN missing romanization for: ${name}`);
  }
  return name;
}

/** locale이 en일 때만 변환하는 편의 헬퍼 */
export function localizedPlaceName(name: string, locale: "ko" | "en"): string {
  return locale === "en" ? placeNameEn(name) : name;
}
